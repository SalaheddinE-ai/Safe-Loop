from enum import StrEnum


class TaskStatus(StrEnum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    SUCCESS = "SUCCESS"
    FAILED_VERIFICATION = "FAILED_VERIFICATION"
    BUDGET_EXHAUSTED = "BUDGET_EXHAUSTED"
    DEADLINE_EXCEEDED = "DEADLINE_EXCEEDED"
    BLOCKED_BY_POLICY = "BLOCKED_BY_POLICY"
    PROVIDER_ERROR = "PROVIDER_ERROR"
    SANDBOX_ERROR = "SANDBOX_ERROR"
    CANCELLED = "CANCELLED"

    @property
    def is_terminal(self) -> bool:
        return self not in (TaskStatus.PENDING, TaskStatus.RUNNING)


class TerminationReason(StrEnum):
    ACCEPTANCE_CRITERIA_MET = "ACCEPTANCE_CRITERIA_MET"
    MAX_ATTEMPTS_REACHED = "MAX_ATTEMPTS_REACHED"
    COST_LIMIT = "COST_LIMIT"
    DEADLINE = "DEADLINE"
    STAGNATION = "STAGNATION"
    POLICY_VIOLATION = "POLICY_VIOLATION"
    NON_REPAIRABLE_FAILURE = "NON_REPAIRABLE_FAILURE"
    PROVIDER_FAILURE = "PROVIDER_FAILURE"
    SANDBOX_UNAVAILABLE = "SANDBOX_UNAVAILABLE"
    USER_CANCELLED = "USER_CANCELLED"


class FailureCategory(StrEnum):
    NONE = "NONE"
    MALFORMED_OUTPUT = "MALFORMED_OUTPUT"
    SYNTAX_ERROR = "SYNTAX_ERROR"
    POLICY_VIOLATION = "POLICY_VIOLATION"
    TEST_FAILURE = "TEST_FAILURE"
    TEST_TIMEOUT = "TEST_TIMEOUT"
    RESOURCE_LIMIT = "RESOURCE_LIMIT"
    INFRASTRUCTURE = "INFRASTRUCTURE"

    @property
    def repairable(self) -> bool:
        return self in _REPAIRABLE


_REPAIRABLE = {
    FailureCategory.MALFORMED_OUTPUT,
    FailureCategory.SYNTAX_ERROR,
    FailureCategory.TEST_FAILURE,
    FailureCategory.TEST_TIMEOUT,
    FailureCategory.RESOURCE_LIMIT,
}


class CostSource(StrEnum):
    REPORTED = "REPORTED"
    ESTIMATED = "ESTIMATED"
    UNAVAILABLE = "UNAVAILABLE"
